# ───────── 1. 법령·규정 발췌 ─────────
reg = (REPO / "ethics-system/backend/seed/regulations.txt").read_text(encoding="utf-8").splitlines()
blocks, cur = {}, None
for line in reg:
    m = re.match(r"^< (.+) >$", line)
    if m:
        cur = m.group(1)
        blocks[cur] = []
        continue
    if cur:
        blocks[cur].append(line)


def articles(law, wanted):
    """law 안에서 '제N조(…)' 또는 '제N조 ' 로 시작하는 조문 덩어리 중 wanted에 든 것만"""
    out, keep = [], False
    for line in blocks[law]:
        if line.replace(" ", "").startswith("부칙"):
            break
        m = re.match(r"^(제\d+조(?:의\d+)?)[\s(]", line)
        if m:
            keep = m.group(1) in wanted
        elif line.replace(" ", "").startswith(("부칙", "제1장", "제2장", "제3장", "제4장", "윤 리")):
            keep = False
        if keep:
            out.append(line.rstrip())
    return out


